import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { runCli } from "../src/index.js";
import { formatMarkdownReport } from "../src/format.js";
import type { Report } from "@stackdoctor/schemas";

describe("StackDoctor CLI CI Mode, Exit Codes & Determinism (Run 4B)", () => {
  const originalLog = console.log;
  const originalError = console.error;
  let loggedOutput: string[] = [];
  let errorOutput: string[] = [];

  beforeEach(() => {
    loggedOutput = [];
    errorOutput = [];
    console.log = (...args: unknown[]) => {
      loggedOutput.push(args.map(String).join(" "));
    };
    console.error = (...args: unknown[]) => {
      errorOutput.push(args.map(String).join(" "));
    };
  });

  afterEach(() => {
    console.log = originalLog;
    console.error = originalError;
  });

  describe("1. Exit Code Matrix for Every Severity Threshold", () => {
    // examples/broken-node-project contains HIGH and MEDIUM findings, but NO CRITICAL findings
    it("--fail-on info returns exit code 1 when findings are present", async () => {
      const exitCode = await runCli(["scan", "examples/broken-node-project", "--ci", "--fail-on", "info"]);
      expect(exitCode).toBe(1);
    });

    it("--fail-on low returns exit code 1 when findings are present", async () => {
      const exitCode = await runCli(["scan", "examples/broken-node-project", "--ci", "--fail-on", "low"]);
      expect(exitCode).toBe(1);
    });

    it("--fail-on medium returns exit code 1 when medium findings are present", async () => {
      const exitCode = await runCli(["scan", "examples/broken-node-project", "--ci", "--fail-on", "medium"]);
      expect(exitCode).toBe(1);
    });

    it("--fail-on high returns exit code 1 when high findings are present (default threshold)", async () => {
      const exitCode = await runCli(["scan", "examples/broken-node-project", "--ci", "--fail-on", "high"]);
      expect(exitCode).toBe(1);
    });

    it("--fail-on critical returns exit code 0 when no critical findings exist", async () => {
      const exitCode = await runCli(["scan", "examples/broken-node-project", "--ci", "--fail-on", "critical"]);
      expect(exitCode).toBe(0);
    });

    it("returns exit code 0 on a clean project for all thresholds", async () => {
      const exitCodeInfo = await runCli(["scan", "examples/healthy-node-project", "--ci", "--fail-on", "info"]);
      expect(exitCodeInfo).toBe(0);

      const exitCodeCrit = await runCli(["scan", "examples/healthy-node-project", "--ci", "--fail-on", "critical"]);
      expect(exitCodeCrit).toBe(0);
    });
  });

  describe("2. CI Flag Guarantees (No ANSI, Non-Interactive)", () => {
    it("--ci output contains zero ANSI color escape sequences", async () => {
      const exitCode = await runCli(["scan", "examples/broken-node-project", "--ci", "--format", "text"]);
      expect(exitCode).toBe(1);

      const fullOutput = loggedOutput.join("\n");
      const hasAnsi = fullOutput.includes("\x1b[") || fullOutput.includes("\u001b[");
      expect(hasAnsi).toBe(false);
    });
  });

  describe("3. Deterministic Output Across Multiple Runs", () => {
    it("produces deterministically ordered findings across two consecutive runs", async () => {
      // Run 1
      loggedOutput = [];
      await runCli(["scan", "examples/broken-node-project", "--ci", "--format", "json"]);
      const report1: Report = JSON.parse(loggedOutput.join("\n"));

      // Run 2
      loggedOutput = [];
      await runCli(["scan", "examples/broken-node-project", "--ci", "--format", "json"]);
      const report2: Report = JSON.parse(loggedOutput.join("\n"));

      expect(report1.findings.length).toBe(report2.findings.length);
      expect(report1.findings.length).toBeGreaterThan(0);

      const findingsSignature1 = report1.findings.map((f) => `${f.severity}:${f.ruleId}`);
      const findingsSignature2 = report2.findings.map((f) => `${f.severity}:${f.ruleId}`);

      expect(findingsSignature1).toEqual(findingsSignature2);
    });
  });

  describe("4. Markdown Summary Format & Snapshot", () => {
    it("renders Markdown summary compatible with GitHub Step Summaries", async () => {
      loggedOutput = [];
      const exitCode = await runCli(["scan", "examples/broken-node-project", "--ci", "--format", "markdown"]);
      expect(exitCode).toBe(1);

      const markdown = loggedOutput.join("\n");
      expect(markdown).toContain("## StackDoctor Diagnostic Summary:");
      expect(markdown).toContain("### Findings by Severity");
      expect(markdown).toContain("| Critical | High | Medium | Low | Info |");
      expect(markdown).toContain("### Detected Issues");
      expect(markdown).toContain("<details>");
      expect(markdown).toContain("<summary><strong>Finding Details & Recommendations</strong>");
      expect(markdown).toContain("<sub>Generated by StackDoctor");
    });

    it("matches markdown format snapshot for canonical report", () => {
      const sampleReport: Report = {
        schemaVersion: "1.0.0",
        toolVersion: "0.1.0",
        operatingSystem: "linux",
        startedAt: "2026-10-26T12:00:00.000Z",
        completedAt: "2026-10-26T12:00:02.000Z",
        status: "completed_with_warnings",
        projectName: "demo-service",
        technologies: [{ name: "Node.js", confidence: "confirmed", evidence: [] }],
        checks: [],
        findings: [
          {
            ruleId: "NODE_DEPS_NOT_INSTALLED",
            title: "Dependencies missing in node_modules",
            category: "dependencies",
            severity: "high",
            confidence: "confirmed",
            status: "failed",
            evidence: [
              {
                id: "ev1",
                kind: "filesystem",
                description: "node_modules missing",
                observed: "Directory not found",
                source: "fs.existsSync",
                collectedAt: "2026-10-26T12:00:01.000Z"
              }
            ],
            possibleCauses: ["Run npm install"],
            recommendations: [
              {
                problem: "Dependencies missing",
                relevance: "Required to run",
                commandOrAction: "npm install",
                expectedResult: "node_modules populated",
                risks: "None",
                verification: "test -d node_modules"
              }
            ],
            verificationStatus: "unverified",
            docs: []
          }
        ],
        summary: {
          totalChecks: 1,
          totalFindings: 1,
          bySeverity: {
            critical: 0,
            high: 1,
            medium: 0,
            low: 0,
            info: 0
          },
          byStatus: {
            passed: 0,
            warning: 0,
            failed: 1,
            skipped: 0,
            error: 0
          }
        }
      };

      const markdown = formatMarkdownReport(sampleReport);
      expect(markdown).toMatchSnapshot();
    });
  });

  describe("5. Invalid Flag and Usage Returns Exit Code 3", () => {
    it("returns exit code 3 on unrecognized flag", async () => {
      const exitCode = await runCli(["scan", "--unrecognized-flag-foo"]);
      expect(exitCode).toBe(3);
      expect(errorOutput.join("\n")).toContain("Usage error: Unknown flag");
    });

    it("returns exit code 3 on invalid --fail-on value", async () => {
      const exitCode = await runCli(["scan", "--fail-on", "bogus_severity"]);
      expect(exitCode).toBe(3);
      expect(errorOutput.join("\n")).toContain("Usage error: Invalid severity");
    });

    it("returns exit code 3 on invalid --format value", async () => {
      const exitCode = await runCli(["scan", "--format", "bogus_format"]);
      expect(exitCode).toBe(3);
      expect(errorOutput.join("\n")).toContain("Usage error: Invalid value");
    });

    it("returns exit code 3 when required flag argument is missing", async () => {
      const exitCode = await runCli(["scan", "--fail-on"]);
      expect(exitCode).toBe(3);
      expect(errorOutput.join("\n")).toContain("Usage error: Missing severity value");
    });
  });
});
